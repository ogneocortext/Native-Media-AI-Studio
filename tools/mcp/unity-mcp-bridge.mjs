#!/usr/bin/env node
/**
 * Unity MCP Bridge for Kilo Code
 * Wraps the `unity` CLI as a local MCP server.
 */

import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { readFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { z } from "zod";

const __dirname = dirname(fileURLToPath(import.meta.url));
// Use environment variable or derive from repo root (tools/mcp -> ../../)
const DEFAULT_PROJECT_PATH = join(__dirname, "..", "..", "unity-project-mcp");
// Handle both relative and absolute paths
let PROJECT_PATH = process.env.UNITY_PROJECT_PATH || DEFAULT_PROJECT_PATH;
// Convert relative path to absolute (relative to repo root)
if (!PROJECT_PATH.includes(":") && !PROJECT_PATH.startsWith("/")) {
  PROJECT_PATH = join(__dirname, "..", "..", PROJECT_PATH);
}

function getPortInfo() {
  try {
    const raw = readFileSync(
      join(PROJECT_PATH, "Library", "Pipeline", ".unity-pipeline-port"),
      "utf-8",
    );
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

async function execUnity(command, parameters = {}) {
  const info = getPortInfo();
  if (!info) return { error: "Unity MCP server not running (no port file)" };
  const res = await fetch(`http://127.0.0.1:${info.port}/api/exec`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${info.evalToken}`,
    },
    body: JSON.stringify({ command, parameters }),
  });
  return res.json();
}

async function listCommands() {
  const info = getPortInfo();
  if (!info) return [];
  const res = await fetch(
    `http://127.0.0.1:${info.port}/api/commands?detail=compact`,
    { headers: { Authorization: `Bearer ${info.evalToken}` } },
  );
  const data = await res.json();
  return data.commands || [];
}

// Create MCP server
const server = new McpServer(
  { name: "unity-mcp-bridge", version: "1.1.0" },
  { capabilities: { tools: {} } },
);

// Register a generic "unity_command" tool that proxies any Unity command
server.registerTool(
  "unity_command",
  {
    description:
      "Execute a Unity Editor command. Use this to create GameObjects, add components, control animation, capture screenshots, build, and more.",
    inputSchema: {
      command: z
        .string()
        .describe(
          "Unity command name (e.g., create_gameobject, add_component, capture_scene_view)",
        ),
      parameters: z
        .record(z.any())
        .describe("Command parameters as key-value pairs"),
    },
  },
  async ({ command, parameters }) => {
    const result = await execUnity(command, parameters || {});
    return {
      content: [{ type: "text", text: JSON.stringify(result, null, 2) }],
    };
  },
);

// Register specific commonly-used tools
const commonTools = [
  {
    name: "create_gameobject",
    desc: "Create a GameObject or primitive (cube/sphere/capsule/cylinder/plane/quad)",
    params: {
      name: z.string().optional(),
      primitive: z
        .enum(["cube", "sphere", "capsule", "cylinder", "plane", "quad"])
        .optional(),
    },
  },
  {
    name: "add_component",
    desc: "Add a component to a GameObject",
    params: { target: z.string(), type: z.string() },
  },
  {
    name: "capture_scene_view",
    desc: "Capture the Scene View to a PNG file",
    params: {
      save_path: z.string(),
      width: z.number().optional(),
      height: z.number().optional(),
    },
  },
  {
    name: "editor_status",
    desc: "Get Unity Editor status (compiling, play mode, etc.)",
    params: {},
  },
  {
    name: "create_scene",
    desc: "Create a new scene",
    params: { path: z.string() },
  },
  {
    name: "create_animation_clip",
    desc: "Create an AnimationClip asset",
    params: {
      path: z.string(),
      frameRate: z.number().optional(),
      loop: z.boolean().optional(),
    },
  },
];

for (const tool of commonTools) {
  server.registerTool(
    tool.name,
    { description: tool.desc, inputSchema: tool.params },
    async (params) => {
      const result = await execUnity(tool.name, params);
      return {
        content: [{ type: "text", text: JSON.stringify(result, null, 2) }],
      };
    },
  );
}

// Start

/**
 * Read beat_data.json from the tools/output directory to get tempo, beat_times, and keyframes.
 * This file is generated by tools/analyze_and_sync.py.
 */
function getBeatData() {
  try {
    const beatDataPath = join(__dirname, "..", "output", "beat_data.json");
    return JSON.parse(readFileSync(beatDataPath, "utf-8"));
  } catch {
    return null;
  }
}

// Music-video-specific tools

server.registerTool(
  "get_beat_data",
  {
    description:
      "Read beat_data.json generated by analyze_and_sync.py. Returns tempo (BPM), beat_times, and 24fps keyframes for music-synchronized animation.",
    inputSchema: {},
  },
  async () => {
    const data = getBeatData();
    if (!data) {
      return {
        content: [
          {
            type: "text",
            text: JSON.stringify(
              {
                error:
                  "beat_data.json not found. Run: python tools/analyze_and_sync.py <audio_file>",
              },
              null,
              2,
            ),
          },
        ],
      };
    }
    return { content: [{ type: "text", text: JSON.stringify(data, null, 2) }] };
  },
);

server.registerTool(
  "create_beat_animation",
  {
    description:
      "Create an AnimationClip with keyframes at each beat interval. Uses beat_data.json for timing. Animates the target object's localScale for a pulsing effect synced to the music beat.",
    inputSchema: {
      object_name: z.string().describe("Name of the GameObject to animate"),
      clip_path: z
        .string()
        .describe(
          "Asset path for the AnimationClip (e.g., Assets/Animations/beat_anim.anim)",
        ),
      pulse_scale: z
        .number()
        .default(1.5)
        .describe("Max scale multiplier on each beat"),
      frame_rate: z.number().default(24).describe("Animation frame rate"),
      max_beats: z.number().optional().describe("Limit to first N beats"),
    },
  },
  async ({
    object_name,
    clip_path,
    pulse_scale = 1.5,
    frame_rate = 24,
    max_beats,
  }) => {
    const beatData = getBeatData();
    if (!beatData) {
      return {
        content: [
          {
            type: "text",
            text: "beat_data.json not found. Run: python tools/analyze_and_sync.py <audio_file>",
          },
        ],
      };
    }
    const keyframes = max_beats
      ? beatData.keyframes.slice(0, max_beats)
      : beatData.keyframes;
    return {
      content: [
        {
          type: "text",
          text: JSON.stringify(
            {
              instructions: `Apply beat-scaled keyframes to '${object_name}' at '${clip_path}'`,
              tempo: beatData.tempo,
              keyframe_count: keyframes.length,
              keyframes,
              params: { pulse_scale, frame_rate },
            },
            null,
            2,
          ),
        },
      ],
    };
  },
);

server.registerTool(
  "capture_frame_sequence",
  {
    description:
      "Generate capture commands for rendering an animation sequence. Defaults to 240 frames at 24fps (10 seconds).",
    inputSchema: {
      fps: z.number().default(24).describe("Frames per second"),
      duration_seconds: z.number().default(10).describe("Duration in seconds"),
      output_dir: z
        .string()
        .describe(
          "Directory to save frames (e.g., Assets/Textures/auto_frame)",
        ),
      width: z.number().default(1280).describe("Output width"),
      height: z.number().default(720).describe("Output height"),
    },
  },
  async ({
    fps = 24,
    duration_seconds = 10,
    output_dir,
    width = 1280,
    height = 720,
  }) => {
    const total = fps * duration_seconds;
    return {
      content: [
        {
          type: "text",
          text: JSON.stringify(
            {
              total_frames: total,
              fps,
              duration_seconds,
              output_dir,
              resolution: { width, height },
              note: `Add AutoCapture.cs to a GameObject and start Play mode, or use capture_scene_view for individual frames.`,
            },
            null,
            2,
          ),
        },
      ],
    };
  },
);

server.registerTool(
  "list_pipeline_commands",
  {
    description: "List all available Unity Pipeline commands (100+ commands).",
    inputSchema: {},
  },
  async () => {
    const commands = await listCommands();
    return {
      content: [{ type: "text", text: JSON.stringify(commands, null, 2) }],
    };
  },
);

const transport = new StdioServerTransport();
await server.connect(transport);
console.error("Unity MCP Bridge running");
